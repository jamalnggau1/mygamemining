-- Jalankan SEKALI pada database Neon yang masih kosong:
--   - Neon Console → SQL Editor → paste seluruh file ini → Run, ATAU
--   - psql "$DATABASE_URL" -f deploy/neon/init.sql
--     (DATABASE_URL dibaca dari environment — jangan pernah menulis
--      string koneksi asli ke file, kode, atau log.)
--
-- File ini adalah skema Postgres untuk game ini (dulu cermin dari
-- skema SQLite di runtime Muse): tabel player, inventory, upgrades,
-- wd_requests, premium_orders, activity. Perbedaan dialect saja:
--   - timestamp mode "timestamp_ms"  → TIMESTAMPTZ
--   - amount_usdt / total_wd_paid_usdt (REAL, langkah 0,1 USDT)
--                                    → DOUBLE PRECISION
--   - KT balance columns (kt_balance, total_kt_earned,
--     activity.amount_kt) → DOUBLE PRECISION sejak rebalance #5
--     (2026-11-19): KT kini pecahan (Regolith 0,1 KT). Bukan
--     NUMERIC — driver mengembalikan NUMERIC sebagai string, yang
--     akan merusak aritmetika saldo di kode; debu float dicegah di
--     kode dengan pembulatan 1 desimal di setiap kredit/debit.
--   - INTEGER PRIMARY KEY AUTOINCREMENT → BIGSERIAL
-- Semua CREATE memakai IF NOT EXISTS, jadi file ini aman dijalankan
-- ulang (idempotent) dan tidak menyentuh data yang sudah ada.
--
-- PER-PLAYER (2026-11-18): setiap pemain Telegram punya baris player
-- sendiri (player.telegram_id, UNIQUE; NULL hanya untuk pemain web
-- lama id=1), dan semua tabel per-pemain membawa player_id supaya
-- saldo, inventory, upgrade, riwayat WD, pesanan Premium, dan log
-- aktivitas terpisah per pemain. Kalau database SUDAH berisi tabel
-- dari versi single-player, JANGAN jalankan file ini untuk migrasi —
-- jalankan deploy/neon/migration-0001-telegram-id.sql sebagai gantinya.
-- =====================================================================

CREATE TABLE IF NOT EXISTS player (
  -- IDENTITY mulai dari 1000: pemain web lama memakai id=1 eksplisit,
  -- dan insert eksplisit tidak memajukan sequence — tanpa ini pemain
  -- Telegram pertama akan bertabrakan dengan id=1.
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  telegram_id BIGINT UNIQUE,
  username TEXT,
  kt_balance DOUBLE PRECISION NOT NULL DEFAULT 0,
  energy INTEGER NOT NULL DEFAULT 20,
  energy_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  layer INTEGER NOT NULL DEFAULT 1,
  current_zone INTEGER NOT NULL DEFAULT 0,
  premium_until TIMESTAMPTZ,
  premium_tier TEXT CHECK (premium_tier IN ('standard', 'pro')),
  grid TEXT NOT NULL DEFAULT '[]',
  expedition TEXT NOT NULL DEFAULT '',
  job TEXT,
  total_scans INTEGER NOT NULL DEFAULT 0,
  asteroids_done INTEGER NOT NULL DEFAULT 0,
  total_digs INTEGER NOT NULL DEFAULT 0,
  total_kt_earned DOUBLE PRECISION NOT NULL DEFAULT 0,
  total_wd_paid_usdt DOUBLE PRECISION NOT NULL DEFAULT 0,
  -- Anti-cheat otomatis (2026-11-19): skor risiko (0 = bersih),
  -- alasan flag terakhir, kapan terakhir menyala, streak collect
  -- instan, hitungan percobaan aksi mustahil + awal jendelanya, dan
  -- jam epoch evaluasi terakhir. Pemain dengan risk_score > 0 TIDAK
  -- diblokir main — hanya WD-nya ditandai perlu ditinjau.
  risk_score INTEGER NOT NULL DEFAULT 0,
  flag_reason TEXT,
  flagged_at TIMESTAMPTZ,
  instant_collect_streak INTEGER NOT NULL DEFAULT 0,
  tamper_count INTEGER NOT NULL DEFAULT 0,
  tamper_since TIMESTAMPTZ,
  last_eval_hour INTEGER
);
