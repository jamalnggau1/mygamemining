-- Yang diubah (aturan & ekonomi game TIDAK berubah):
--   1. player.telegram_id BIGINT UNIQUE — id Telegram pemain yang
--      sudah divalidasi server. NULL hanya untuk pemain web lama.
--   2. player.id menjadi IDENTITY — pemain Telegram baru dibuat tanpa
--      id eksplisit (database yang memberi nomor); pemain web lama
--      tetap id = 1.
--   3. inventory / upgrades / wd_requests / premium_orders / activity
--      mendapat kolom player_id — semua data yang SUDAH ADA dianggap
--      milik pemain web lama (player_id = 1), jadi saldo & progres
--      yang sudah berjalan TIDAK hilang.
--   4. Primary key inventory/upgrades menjadi komposit
--      (player_id, ore_id) / (player_id, upgrade_id) supaya tiap
--      pemain punya inventory & upgrade sendiri.
--
-- File ini aman dijalankan ulang: kolom memakai IF NOT EXISTS dan
-- perubahan constraint dijaga blok DO (tidak error bila sudah
-- diterapkan). Setelah migrasi, jalankan juga redeploy Vercel dari
-- kode terbaru dan set BOT_TOKEN + ADMIN_TELEGRAM_ID di Vercel
-- (lihat deploy/README.md).
