-- 1. player.telegram_id -------------------------------------------------
ALTER TABLE player ADD COLUMN IF NOT EXISTS telegram_id BIGINT UNIQUE;

-- 2. player.id menjadi IDENTITY (START WITH 1000) ----------------------
-- Pemain web lama memakai id=1 eksplisit, dan insert eksplisit tidak
-- memajukan sequence — START WITH 1000 memastikan pemain Telegram
-- pertama mendapat id >= 1000, bukan 1 (tanpa ini insert identity
-- pertama akan bertabrakan dengan baris id=1). DROP + ADD ulang
-- diperlukan bila identity sudah ada dengan start 1: ALTER tidak
-- bisa mengubah start sequence identity, dan TRUNCATE ...
-- RESTART IDENTITY akan mengembalikannya ke start lama.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'player'
      AND column_name = 'id' AND is_identity = 'NO'
  ) THEN
    ALTER TABLE player ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
  ELSIF EXISTS (
    SELECT 1 FROM pg_sequence
    WHERE seqrelid = pg_get_serial_sequence('player', 'id')::regclass
      AND seqstart < 1000
  ) THEN
    ALTER TABLE player ALTER COLUMN id DROP IDENTITY IF EXISTS;
    ALTER TABLE player ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
    -- Jangan sampai sequence mundur ke id yang sudah terpakai.
    PERFORM setval(
      pg_get_serial_sequence('player', 'id'),
      GREATEST(999, (SELECT COALESCE(MAX(id), 0) FROM player)),
      true
    );
  END IF;
END $$;

-- 3a. inventory.player_id + PK komposit ---------------------------------
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS player_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE inventory ALTER COLUMN player_id DROP DEFAULT;
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'inventory_pkey' AND conrelid = 'inventory'::regclass
  ) THEN
    ALTER TABLE inventory DROP CONSTRAINT inventory_pkey;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'inventory_pkey' AND conrelid = 'inventory'::regclass
  ) THEN
    ALTER TABLE inventory ADD PRIMARY KEY (player_id, ore_id);
  END IF;
END $$;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'inventory_player_fk' AND conrelid = 'inventory'::regclass
  ) THEN
    ALTER TABLE inventory ADD CONSTRAINT inventory_player_fk
      FOREIGN KEY (player_id) REFERENCES player (id);
  END IF;
END $$;

