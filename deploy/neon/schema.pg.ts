// Anti-cheat otomatis (2026-11-19): jejak audit setiap aturan
// deteksi yang menyala (dan setiap pembersihan flag oleh admin).
// Satu baris per kejadian — alasan lengkapnya tinggal di sini,
// sementara player.flag_reason hanya ringkasan terakhir untuk
// ditampilkan di Kendali. Bukan tabel hukuman: baris di sini tidak
// pernah memblokir pemain main.
export const securityFlags = pgTable(
  "security_flags",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    // Aturan yang menyala: nonstop | instant_collect | multi_account
    // | tamper | flag_cleared (audit pembersihan oleh admin).
    rule: text("rule").notNull(),
    reason: text("reason").notNull(),
    points: integer("points").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
  },
  (t) => [index("security_flags_player_idx").on(t.playerId, t.createdAt)],
);

// Anti-cheat otomatis (2026-11-19): IP terakhir yang terlihat per
// pemain — bahan aturan multi-akun (c). IP diambil server dari header
// x-forwarded-for (Vercel edge), TIDAK PERNAH dari kiriman klien.
// last_seen_at diperbarui max 1×/jam/pemain, bukan tiap request.
export const playerIp = pgTable(
  "player_ip",
  {
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    ip: text("ip").notNull(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.playerId, t.ip] }),
    index("player_ip_ip_idx").on(t.ip, t.lastSeenAt),
  ],
);

// PvP (2026-11-22): pasukan per pemain — dua jenis, 'attack'
// (Drone Serbu) dan 'defense' (Drone Perisai). count = jumlah
// drone, level = level teknologi (mulai 1). Kekuatan =
// count × (6 + 4×level). Beli + upgrade pakai KT yang sama dengan
// saldo WD (satu mata uang — itu dilemanya).
export const pvpTroops = pgTable(
  "pvp_troops",
  {
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    kind: text("kind", { enum: ["attack", "defense"] }).notNull(),
    count: integer("count").notNull().default(0),
    level: integer("level").notNull().default(1),
  },
  (t) => [primaryKey({ columns: [t.playerId, t.kind] })],
);

// PvP (2026-11-22): jejak audit setiap pertempuran — siapa
// menyerang siapa, NPC atau pemain, siapa menang, kekuatan kedua
// pihak, dan nilai KT rampasan (0 bila tidak ada yang dirampas).
export const pvpBattles = pgTable(
  "pvp_battles",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    attackerPlayerId: integer("attacker_player_id")
      .notNull()
      .references(() => player.id),
    defenderPlayerId: integer("defender_player_id").references(
      () => player.id,
    ),
    isNpc: boolean("is_npc").notNull().default(false),
    winner: text("winner", { enum: ["attacker", "defender"] }).notNull(),
    attackerPower: integer("attacker_power").notNull(),
    defenderPower: integer("defender_power").notNull(),
    lootKt: doublePrecision("loot_kt").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("pvp_battles_attacker_idx").on(t.attackerPlayerId, t.createdAt),
    index("pvp_battles_defender_idx").on(t.defenderPlayerId, t.createdAt),
  ],
);

// Referral (2026-11-20): satu baris per pemain yang diundang —
// siapa pengundangnya, siapa yang diundang, dan apakah hadiah 10 KT
// sudah dibayarkan. Atribusi dicatat sekali saat pemain baru dibuat
// lewat link referral (lihat recordReferralAttribution di
// api/_lib/game.ts); hadiah dibayar saat pemain yang diundang
// menyelesaikan ekspedisi PERTAMANYA (lihat
// payReferralRewardIfPending). UNIQUE di referred_player_id:
// satu pemain yang diundang hanya bisa punya satu pengundang,
// selamanya — atribusi ulang tidak mungkin. status "pending" =
// menunggu ekspedisi pertama; "rewarded" = 10 KT sudah masuk ke
// saldo pengundang.
export const referrals = pgTable(
  "referrals",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    referrerPlayerId: integer("referrer_player_id")
      .notNull()
      .references(() => player.id),
    referredPlayerId: integer("referred_player_id")
      .notNull()
      .references(() => player.id)
      .unique(),
    status: text("status", { enum: ["pending", "rewarded"] })
      .notNull()
      .default("pending"),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
    rewardedAt: timestamp("rewarded_at", {
      withTimezone: true,
      mode: "date",
    }),
  },
  (t) => [index("referrals_referrer_idx").on(t.referrerPlayerId)],
);
