// Postgres (Neon) schema for the Vercel deployment. Same table
// names, same column property names, same game
// semantics — only the dialect differs:
//   - SQLite integer "timestamp_ms" columns become TIMESTAMPTZ
//     (mode: "date", so handlers keep working with Date objects).
//   - wd amount columns stay floating point (DOUBLE PRECISION) because
//     WD amounts move in 0,1 USDT steps.
//   - KT balance columns are DOUBLE PRECISION too (rebalance #5,
//     2026-11-19): KT is fractional now (Regolith 0,1 KT), so
//     kt_balance, total_kt_earned and activity.amount_kt hold
//     1-decimal values. DOUBLE PRECISION — not NUMERIC — because
//     Drizzle maps it to a JS number in both drivers (Neon HTTPS
//     and node-postgres); NUMERIC comes back as a string and would
//     break every `p.ktBalance + x` (string concat) and every
//     `z.number()` check. Float dust is prevented in code instead:
//     every credit/debit is rounded to 1 decimal at the point it
//     touches the balance (roundKt in api/_lib/game.ts).
//   - AUTOINCREMENT ids become BIGSERIAL identities.
// The DDL twin of this file is deploy/neon/init.sql — keep them in
// sync. The game handlers in api/_lib/game.ts are written against
// the Drizzle query builder, so porting them to Neon means pointing
// the same queries at a drizzle-orm/neon-http database built from
// this schema (see deploy/README.md).
//
// PER-PLAYER SESSIONS (2026-11-18): the game is no longer single
// player. Every Telegram player gets their OWN player row, keyed by
// their validated Telegram user id (`player.telegram_id`, UNIQUE,
// NULL only for the legacy web player id=1), and every per-player
// table carries `player_id` so balances, inventory, upgrades, WD
// history, premium orders and the activity log are isolated per
// player. inventory/upgrades use composite primary keys
// (player_id, ore_id) / (player_id, upgrade_id). The admin
// (Kendali) queue reads across all players — that is the ONLY place
// a query is not scoped to one player.

import {
  bigint,
  bigserial,
  boolean,
  doublePrecision,
  index,
  integer,
  pgTable,
  primaryKey,
  real,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";

export const player = pgTable("player", {
  // GENERATED BY DEFAULT AS IDENTITY: Telegram players are created
  // without an explicit id (the database assigns one); the legacy
  // web player keeps its explicit id = 1. START WITH 1000 reserves
  // ids 1..999 so the sequence can never hand out id=1 to a Telegram
  // player (explicit inserts do not advance the sequence — without
  // this, the first Telegram player would collide with the legacy
  // row). Mirrored in deploy/neon/init.sql.
  id: integer("id")
    .generatedByDefaultAsIdentity({ startWith: 1000 })
    .primaryKey(),
  // Validated Telegram user id. UNIQUE so one Telegram account can
  // never own two player rows; NULL only for the legacy web player.
  telegramId: bigint("telegram_id", { mode: "number" }).unique(),
  // Username Telegram terakhir yang terlihat di initData yang
  // tervalidasi (hanya untuk dikenali admin di daftar pemain
  // mencurigakan — identitas tetap telegram_id, bukan username).
  username: text("username"),
  // Nama depan Telegram terakhir (untuk daftar teman referral di tab
  // Komunitas — "Andi" lebih dikenali daripada @username; banyak
  // pemain tidak punya username). Diisi loadPlayer dari initData.
  firstName: text("first_name"),
  ktBalance: doublePrecision("kt_balance").notNull().default(0),
  energy: integer("energy").notNull().default(20),
  energyUpdatedAt: timestamp("energy_updated_at", {
    withTimezone: true,
    mode: "date",
  })
    .notNull()
    .defaultNow(),
  layer: integer("layer").notNull().default(1),
  // Progres sektor (2026-11-20): ekspedisi yang sudah diselesaikan
  // di sektor saat ini. Naik dari sektor L ke L+1 butuh L ekspedisi
  // (1→2 butuh 1, 2→3 butuh 2, ...); saat sektor naik, kembali 0.
  // Ini yang membuat peta jauh sulit dicapai (Sektor 20 = 190
  // ekspedisi total sejak 2026-11-21) — bukan timer, melainkan jumlah ekspedisi.
  sectorProgress: integer("sector_progress").notNull().default(0),
  currentZone: integer("current_zone").notNull().default(0),
  premiumUntil: timestamp("premium_until", {
    withTimezone: true,
    mode: "date",
  }),
  premiumTier: text("premium_tier", { enum: ["standard", "pro"] }),
  grid: text("grid").notNull().default("[]"),
  expedition: text("expedition").notNull().default(""),
  job: text("job"),
  totalScans: integer("total_scans").notNull().default(0),
  asteroidsDone: integer("asteroids_done").notNull().default(0),
  totalDigs: integer("total_digs").notNull().default(0),
  totalKtEarned: doublePrecision("total_kt_earned").notNull().default(0),
  totalWdPaidUsdt: doublePrecision("total_wd_paid_usdt").notNull().default(0),
  // -- Anti-cheat otomatis (deteksi bot, 2026-11-19) -----------------
  // Skor risiko: 0 = bersih. Setiap aturan deteksi yang menyala
  // menambah skor (lihat api/_lib/anticheat.ts) dan mengisi
  // flag_reason + flagged_at. Pemain dengan risk_score > 0 TIDAK
  // diblokir main — hanya WD-nya ditandai perlu ditinjau dan ia
  // muncul di daftar "Pemain Mencurigakan" Kendali. Hanya admin yang
  // bisa membersihkan flag (aksi clearPlayerFlag).
  riskScore: integer("risk_score").notNull().default(0),
  flagReason: text("flag_reason"),
  flaggedAt: timestamp("flagged_at", { withTimezone: true, mode: "date" }),
  // Streak collect instan berturut-turut (aturan b): naik tiap
  // collect ≤10 detik setelah job selesai, reset bila collect
  // lambat, reset juga saat aturan menyala.
  instantCollectStreak: integer("instant_collect_streak").notNull().default(0),
  // Percobaan aksi mustahil (aturan d): collect sebelum job selesai
  // / scan-bor kedua saat operasi berjalan. tamperSince = awal
  // jendela 24 jam hitungan ini.
  tamperCount: integer("tamper_count").notNull().default(0),
  tamperSince: timestamp("tamper_since", { withTimezone: true, mode: "date" }),
  // Jam epoch terakhir evaluasi aturan (a) + (c) untuk pemain ini —
  // evaluasi dibatasi max 1×/jam/pemain supaya getGameState yang
  // di-poll tiap 5 detik tidak membebani database.
  lastEvalHour: integer("last_eval_hour"),
  // Kapan baris pemain ini dibuat — fallback logika pengingat
  // tidak aktif (migrasi 0009): pemain tanpa baris activity sama
  // sekali dinilai dari tanggal ini.
  createdAt: timestamp("created_at", {
    withTimezone: true,
    mode: "date",
  })
    .notNull()
    .defaultNow(),
  // Pengingat tidak aktif (2026-11-21, migrasi 0009): kapan
  // terakhir pemain ini dikirimi pengingat 3-hari-tidak-aktif.
  // NULL = belum pernah. Cron mengisi ini tiap kali pengingat
  // terkirim; jeda minimum antar pengingat 7 hari.
  lastInactiveNudgeAt: timestamp("last_inactive_nudge_at", {
    withTimezone: true,
    mode: "date",
  }),
  // Bahasa terakhir yang dipilih pemain (2026-11-24, migrasi
  // 0011): disimpan dari `lang` tiap request supaya pesan otomatis
  // (notifikasi WD, pengingat tidak aktif) dikirim dalam bahasa
  // PENERIMA, bukan bahasa admin/pengirim. Default "id".
  language: text("language").notNull().default("id"),
  // PvP (2026-11-22, migrasi 0010): perisai 1 jam setelah diserang
  // (menang/kalah), kapan terakhir menyerang (cooldown 30 menit
  // antar serangan), dan penawaran pertemuan yang sedang aktif
  // (JSON, NULL = tidak ada; kedaluwarsa 10 menit / scan berikut).
  pvpShieldUntil: timestamp("pvp_shield_until", {
    withTimezone: true,
    mode: "date",
  }),
  pvpLastAttackAt: timestamp("pvp_last_attack_at", {
    withTimezone: true,
    mode: "date",
  }),
  pvpEncounter: text("pvp_encounter"),
});

export const inventory = pgTable(
  "inventory",
  {
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    oreId: text("ore_id").notNull(),
    qty: integer("qty").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.playerId, t.oreId] })],
);

export const upgrades = pgTable(
  "upgrades",
  {
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    upgradeId: text("upgrade_id").notNull(),
    level: integer("level").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.playerId, t.upgradeId] })],
);

export const wdRequests = pgTable(
  "wd_requests",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    walletAddress: text("wallet_address").notNull(),
    amountKt: integer("amount_kt").notNull(),
    amountUsdt: doublePrecision("amount_usdt").notNull(),
    status: text("status", {
      enum: ["pending", "approved", "paid", "rejected", "cancelled"],
    })
      .notNull()
      .default("pending"),
    adminNote: text("admin_note"),
    txRef: text("tx_ref"),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
    processedAt: timestamp("processed_at", {
      withTimezone: true,
      mode: "date",
    }),
  },
  (t) => [index("wd_requests_player_idx").on(t.playerId)],
);

export const premiumOrders = pgTable(
  "premium_orders",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    playerId: integer("player_id")
      .notNull()
      .references(() => player.id),
    plan: text("plan").notNull(),
    stars: integer("stars").notNull(),
    days: integer("days").notNull(),
    tier: text("tier", { enum: ["standard", "pro"] }).notNull(),
    status: text("status", {
      enum: ["pending", "confirmed", "rejected", "paid"],
    })
      .notNull()
      .default("pending"),
    // Bukti bayar Telegram Stars (XTR) — diisi webhook
    // /api/telegram-webhook saat successful_payment diterima:
    // telegram_payment_charge_id = id unik bukti bayar dari
    // Telegram, total_amount = Stars yang benar-benar dibayar
    // (dicocokkan dengan kolom stars). Null untuk pesanan manual
    // (konfirmasi Kendali) dan untuk pesanan yang belum dibayar.
    telegramPaymentChargeId: text("telegram_payment_charge_id"),
    totalAmount: integer("total_amount"),
    // Cara bayar (2026-11-20, GRAM/TON Connect): "stars" (invoice
    // XTR) atau "gram" (TON Connect). gram_amount = harga paket
    // dalam GRAM (Standard 4, Pro 13); tx_hash = hash transaksi
    // TON yang membayar (bukti on-chain, UNIQUE — satu hash hanya
    // untuk satu pesanan). Ketiganya null/default untuk pesanan
    // Stars lama.
    method: text("method", { enum: ["stars", "gram"] })
      .notNull()
      .default("stars"),
    gramAmount: real("gram_amount"),
    txHash: text("tx_hash"),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .notNull()
      .defaultNow(),
    processedAt: timestamp("processed_at", {
      withTimezone: true,
      mode: "date",
    }),
  },
  (t) => [
    index("premium_orders_player_idx").on(t.playerId),
    uniqueIndex("premium_orders_tx_hash_unique")
      .on(t.txHash)
      .where(sql`"tx_hash" IS NOT NULL`),
  ],
);

